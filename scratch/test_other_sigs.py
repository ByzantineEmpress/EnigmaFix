def find_pattern(sig_bytes, mask):
    matches = []
    sig_len = len(sig_bytes)
    for i in range(len(data) - sig_len):
        match = True
        for j in range(sig_len):
            if mask[j] == 'x' and data[i+j] != sig_bytes[j]:
                match = False
                break
        if match:
            matches.append(hex(i))
    return matches

